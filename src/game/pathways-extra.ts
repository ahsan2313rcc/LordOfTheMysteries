import type { PathwayDef, SequenceDef } from "./types";

/** Compact Seq builder — early Acting is ability-completable. */
function seqs(
  rows: Array<{
    sequence: number;
    title: string;
    spGain: number;
    abilityName: string;
    abilityCost: number;
    abilityText: string;
    abilityId: string;
    actingCondition: string;
    actingId: string;
    recipe: SequenceDef["recipe"];
    sanityToll: number;
  }>,
): SequenceDef[] {
  return rows.map((r) => ({ ...r }));
}

