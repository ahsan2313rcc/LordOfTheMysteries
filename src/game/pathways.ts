export function getPathway(id: string): PathwayDef {
  const p = PATHWAYS.find((x) => x.id === id);
  if (!p) throw new Error(`Unknown pathway ${id}`);
  return p;
}

export function getSequence(pathwayId: string, sequence: number) {
  return getPathway(pathwayId).sequences.find((s) => s.sequence === sequence)!;
}

export function spGainFor(pathwayId: string, sequence: number): number {
  return getSequence(pathwayId, sequence).spGain;
}
